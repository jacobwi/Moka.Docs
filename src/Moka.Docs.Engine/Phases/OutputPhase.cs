using System.IO.Abstractions;
using System.Web;
using Microsoft.Extensions.Logging;
using Moka.Docs.Core.Configuration;
using Moka.Docs.Core.Content;
using Moka.Docs.Core.Pipeline;
using Moka.Docs.Core.Theming;
using Moka.Docs.Engine.Minification;
using Moka.Docs.Themes;

namespace Moka.Docs.Engine.Phases;

/// <summary>
///     Writes all rendered pages and copies assets to the output directory.
///     Handles output directory creation and cleaning.
/// </summary>
public sealed class OutputPhase(ThemeResolver themeResolver, ILogger<OutputPhase> logger) : IBuildPhase
{
	/// <inheritdoc />
	public string Name => "Output";

	/// <inheritdoc />
	public int Order => 1100;

	/// <inheritdoc />
	public Task ExecuteAsync(BuildContext context, CancellationToken ct = default)
	{
		IFileSystem fs = context.FileSystem;
		string outputDir = OutputPaths.NormalizeDirectory(fs, context.OutputDirectory);

		// Checked before the dry-run exit so validate and doctor report it too. Both paths go
		// through the context's file system first: a mock file system roots "/project" on a
		// different drive than System.IO does, and comparing one of each would never match.
		string? conflict = OutputDirectoryGuard.FindConflict(
			context.Config, fs.Path.GetFullPath(context.RootDirectory), outputDir);
		conflict ??= context.Config.Build.Clean ? OutputDirectoryGuard.FindForeignContent(fs, outputDir) : null;
		if (conflict is not null)
		{
			if (context.DryRun)
			{
				context.Diagnostics.Error(conflict, Name);
				return Task.CompletedTask;
			}

			// Phases normally record a diagnostic and carry on. Carrying on here means
			// deleting the user's sources, so the build has to stop.
			throw new InvalidOperationException(conflict);
		}

		ReportDuplicateRoutes(context);

		// Planned before the clean, so a route that can't be written is reported and skipped
		// instead of failing the build after the previous site was already deleted.
		List<PageWrite> pageWrites = PlanPageWrites(context, outputDir);

		if (context.DryRun)
		{
			// Most important of the three guards: this phase deletes the output directory.
			logger.LogInformation("Dry run: skipping output (no clean, no files written)");
			return Task.CompletedTask;
		}

		// Clean output directory if configured
		if (context.Config.Build.Clean && fs.Directory.Exists(outputDir))
		{
			logger.LogInformation("Cleaning output directory: {Path}", outputDir);
			fs.Directory.Delete(outputDir, true);
		}

		fs.Directory.CreateDirectory(outputDir);

		// Written first, so a build that stops halfway still leaves a folder clean may delete.
		fs.File.WriteAllText(fs.Path.Combine(outputDir, OutputDirectoryGuard.MarkerFileName),
			"This folder is generated by MokaDocs. mokadocs clean and the build's clean step delete it.\n");

		int writtenCount = WritePages(context, pageWrites, ct);

		// Generate section index pages (redirects) for directories without index.html
		int redirectCount = GenerateSectionIndexPages(context, outputDir, pageWrites);

		// Write 404 page
		Write404Page(context);

		// Write .nojekyll
		WriteNoJekyll(context);

		// Write search index JSON
		WriteSearchIndex(context);

		// Copy static assets
		int assetsCopied = CopyAssets(context);

		// Write deferred files registered by plugins (run after clean so they survive)
		int deferredFiles = WriteDeferredFiles(context);
		int deferredDirs = CopyDeferredDirectories(context);

		logger.LogInformation(
			"Wrote {Pages} pages, {Redirects} section redirects, {Assets} assets, {DeferredFiles} deferred files, {DeferredDirs} deferred directories to {Output}",
			writtenCount, redirectCount, assetsCopied, deferredFiles, deferredDirs, outputDir);

		return Task.CompletedTask;
	}

	/// <summary>
	///     Decides where every page goes, reporting the ones that can't be written. Pages sharing
	///     a file keep the last one, as sequential writing did, so writing in parallel has the
	///     same result.
	/// </summary>
	private List<PageWrite> PlanPageWrites(BuildContext context, string outputDir)
	{
		IFileSystem fs = context.FileSystem;
		StringComparer pathComparer = OperatingSystem.IsWindows() || OperatingSystem.IsMacOS()
			? StringComparer.OrdinalIgnoreCase
			: StringComparer.Ordinal;
		var byPath = new Dictionary<string, int>(pathComparer);
		var writes = new List<PageWrite?>();

		foreach (DocPage page in context.Pages)
		{
			if (!context.IncludeDrafts && page.FrontMatter.Visibility == PageVisibility.Draft)
			{
				continue;
			}

			string label = string.IsNullOrEmpty(page.SourcePath)
				? $"generated page '{page.FrontMatter.Title}'"
				: page.SourcePath;

			if (OutputPaths.FindUnsafeRouteProblem(page.Route) is { } unsafeProblem)
			{
				context.Diagnostics.Error($"{label}: route '{page.Route}' was not written: {unsafeProblem}", Name);
				continue;
			}

			if (OutputPaths.FindNonPortableRouteProblem(page.Route) is { } portability)
			{
				if (OperatingSystem.IsWindows())
				{
					context.Diagnostics.Error($"{label}: route '{page.Route}' was not written: {portability}", Name);
					continue;
				}

				context.Diagnostics.Warning(
					$"{label}: route '{page.Route}' can't be built on Windows: {portability}", Name);
			}

			string? fullPath = OutputPaths.ResolveUnder(fs, outputDir, OutputPaths.RouteToFilePath(page.Route));
			if (fullPath is null)
			{
				context.Diagnostics.Error(
					$"{label}: route '{page.Route}' was not written: it resolves outside the output directory", Name);
				continue;
			}

			if (byPath.TryGetValue(fullPath, out int earlier))
			{
				writes[earlier] = null;
			}

			byPath[fullPath] = writes.Count;
			writes.Add(new PageWrite(page, fullPath));
		}

		return writes.OfType<PageWrite>().ToList();
	}

	private int WritePages(BuildContext context, List<PageWrite> writes, CancellationToken ct)
	{
		IFileSystem fs = context.FileSystem;
		var failures = new string?[writes.Count];
		bool minify = context.Config.Build.Minify;

		void Write(int i)
		{
			PageWrite write = writes[i];
			try
			{
				string html = write.Page.Content.Html;
				fs.Directory.CreateDirectory(fs.Path.GetDirectoryName(write.FullPath)!);
				fs.File.WriteAllText(write.FullPath, minify ? HtmlMinifier.Minify(html) : html);
			}
			catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or NotSupportedException
				                           or ArgumentException)
			{
				failures[i] = $"Could not write route '{write.Page.Route}' to {write.FullPath}: {ex.Message}";
			}
		}

		// MockFileSystem, which the ASP.NET Core host builds into, isn't safe for concurrent writes.
		if (fs is FileSystem)
		{
			Parallel.For(0, writes.Count, new ParallelOptions { CancellationToken = ct }, Write);
		}
		else
		{
			for (int i = 0; i < writes.Count; i++)
			{
				ct.ThrowIfCancellationRequested();
				Write(i);
			}
		}

		int written = writes.Count;
		foreach (string? failure in failures)
		{
			if (failure is not null)
			{
				context.Diagnostics.Error(failure, Name);
				written--;
			}
		}

		return written;
	}

	private int CopyAssets(BuildContext context)
	{
		IFileSystem fs = context.FileSystem;
		string docsPath = fs.Path.GetFullPath(
			fs.Path.Combine(context.RootDirectory, context.Config.Content.Docs));
		int count = 0;
		var copiedFromDocs = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

		foreach (string assetPath in context.DiscoveredAssetFiles)
		{
			string sourcePath = fs.Path.Combine(docsPath, assetPath);
			if (!fs.File.Exists(sourcePath) || ResolveOutputPath(context, assetPath) is not { } destPath)
			{
				continue;
			}

			fs.Directory.CreateDirectory(fs.Path.GetDirectoryName(destPath)!);
			fs.File.Copy(sourcePath, destPath, true);
			copiedFromDocs.Add(destPath);
			count++;
		}

		// Brand assets (site.logo, site.favicon) can live OUTSIDE the content.docs tree
		// - e.g. at the mokadocs.yaml directory level, or above it via `../`. The
		// BrandAssetResolver has already resolved these to (publish URL → source path)
		// pairs during the Discovery phase; we just need to copy each one to its
		// publish location under the output dir.
		foreach (KeyValuePair<string, string> brand in context.BrandAssetFiles)
		{
			string publishUrl = brand.Key;
			string sourcePath = brand.Value;

			if (!fs.File.Exists(sourcePath))
			{
				logger.LogWarning("Brand asset source file disappeared between discovery and output: {Source}",
					sourcePath);
				continue;
			}

			// publishUrl always starts with "/"; strip it to resolve it under the output directory.
			if (ResolveOutputPath(context, publishUrl.TrimStart('/')) is not { } destPath)
			{
				continue;
			}

			// A logo inside content.docs reaches the output through the glob above too, and the
			// glob's copy wins. Only this run's copies count: with build.clean off, the previous
			// build's copy is still there, and skipping every existing file kept an edited logo
			// from ever being updated.
			if (copiedFromDocs.Contains(destPath))
			{
				continue;
			}

			fs.Directory.CreateDirectory(fs.Path.GetDirectoryName(destPath)!);
			fs.File.Copy(sourcePath, destPath, true);
			count++;
		}

		return count;
	}

	/// <summary>
	///     Resolves an output-relative path, or records an error and returns <c>null</c> when it
	///     would be written outside the output directory.
	/// </summary>
	private string? ResolveOutputPath(BuildContext context, string relativePath)
	{
		string? full = OutputPaths.ResolveUnder(context.FileSystem, context.OutputDirectory, relativePath);
		if (full is null)
		{
			context.Diagnostics.Error(
				$"'{relativePath}' was not written: it resolves outside the output directory", Name);
		}

		return full;
	}

	private int WriteDeferredFiles(BuildContext context)
	{
		if (context.DeferredOutputFiles.Count == 0)
		{
			return 0;
		}

		IFileSystem fs = context.FileSystem;
		int count = 0;

		foreach (KeyValuePair<string, byte[]> entry in context.DeferredOutputFiles)
		{
			if (ResolveOutputPath(context, entry.Key) is not { } destFile)
			{
				continue;
			}

			fs.Directory.CreateDirectory(fs.Path.GetDirectoryName(destFile)!);
			fs.File.WriteAllBytes(destFile, entry.Value);
			count++;
		}

		logger.LogInformation("Wrote {Count} deferred output file(s)", count);
		return count;
	}

	private int CopyDeferredDirectories(BuildContext context)
	{
		if (context.DeferredOutputDirectories.Count == 0)
		{
			return 0;
		}

		IFileSystem fs = context.FileSystem;
		int totalFiles = 0;

		foreach ((string sourceDir, string destRelPath) in context.DeferredOutputDirectories)
		{
			if (!Directory.Exists(sourceDir))
			{
				logger.LogWarning("Deferred output directory not found, skipping: {SourceDir}", sourceDir);
				continue;
			}

			if (ResolveOutputPath(context, destRelPath) is not { } destDir)
			{
				continue;
			}

			fs.Directory.CreateDirectory(destDir);

			foreach (string sourceFile in Directory.GetFiles(sourceDir, "*", SearchOption.AllDirectories))
			{
				string relative = Path.GetRelativePath(sourceDir, sourceFile);
				string destFile = fs.Path.Combine(destDir, relative);
				fs.Directory.CreateDirectory(fs.Path.GetDirectoryName(destFile)!);
				fs.File.Copy(sourceFile, destFile, true);
				totalFiles++;
			}
		}

		logger.LogInformation("Copied {Count} deferred output directory(s) ({Files} files total)",
			context.DeferredOutputDirectories.Count, totalFiles);
		return context.DeferredOutputDirectories.Count;
	}

	private void WriteSearchIndex(BuildContext context)
	{
		byte[]? bytes = SearchIndexFile.Bytes(context);
		if (bytes is null)
		{
			logger.LogDebug("No search index to write");
			return;
		}

		IFileSystem fs = context.FileSystem;
		fs.File.WriteAllBytes(fs.Path.Combine(context.OutputDirectory, SearchIndexFile.FileName), bytes);

		logger.LogInformation("Wrote search index ({Count} entries, {Size} bytes)",
			context.SearchIndex?.Count ?? 0, bytes.Length);
	}

	/// <summary>
	///     Writes an empty <c>.nojekyll</c> marker at the site root.
	/// </summary>
	/// <remarks>
	///     GitHub Pages runs Jekyll on branch-based deployments, and Jekyll strips every
	///     directory whose name starts with an underscore. Every site emits <c>_theme/</c>,
	///     and some also emit <c>_media/</c> or the Blazor preview's <c>_preview-wasm/</c>,
	///     so without this marker a deployed site loses its CSS and JS entirely.
	///     <para>
	///         This used to be emitted by the Blazor preview plugin, which meant it only
	///         appeared when that plugin was enabled AND had a published preview host to
	///         copy. Any other site shipped without it.
	///     </para>
	/// </remarks>
	private void WriteNoJekyll(BuildContext context)
	{
		IFileSystem fs = context.FileSystem;
		string path = fs.Path.Combine(context.OutputDirectory, ".nojekyll");

		if (fs.File.Exists(path))
		{
			return;
		}

		fs.File.WriteAllText(path, "");
		logger.LogDebug("Wrote .nojekyll marker");
	}

	/// <summary>
	///     Writes a plain <c>404.html</c> when the render phase couldn't stage the theme's own (a
	///     layout that fails to render). That one is written with the other staged files.
	/// </summary>
	private void Write404Page(BuildContext context)
	{
		if (context.DeferredOutputFiles.ContainsKey(RenderPhase.NotFoundPagePath))
		{
			return;
		}

		IFileSystem fs = context.FileSystem;
		SiteConfig config = context.Config;
		string path = fs.Path.Combine(context.OutputDirectory, RenderPhase.NotFoundPagePath);
		string bp = config.Build.BasePath == "/" ? "" : config.Build.BasePath;

		// Versioned like every page's links: the unversioned URLs kept serving a cached stylesheet
		// from an older release.
		ResolvedTheme theme = themeResolver.Resolve(config, context.RootDirectory, fs);
		string cssUrl = HttpUtility.HtmlAttributeEncode(
			bp + ThemeAssetPhase.VersionedUrl("/_theme/css/main.css", theme, context));
		ThemeText text = ThemeText.For(config);
		string title = HttpUtility.HtmlEncode(text["notFound.title"]);
		string home = $"<a href=\"{HttpUtility.HtmlAttributeEncode(bp)}/\">{HttpUtility.HtmlEncode(text["notFound.home"])}</a>";
		string html = $"""
		               <!DOCTYPE html>
		               {HtmlStart(config, text)}
		               <head>
		               <meta charset="utf-8">
		               <meta name="viewport" content="width=device-width, initial-scale=1">
		               <meta name="robots" content="noindex">
		               <title>{title} - {HttpUtility.HtmlEncode(config.Site.Title)}</title>
		               <link rel="stylesheet" href="{cssUrl}">
		               </head>
		               <body>
		               <main class="content"><article class="page-content">
		               <h1>{title}</h1>
		               <p>{HttpUtility.HtmlEncode(text["notFound.text"])}</p>
		               <p>{HttpUtility.HtmlEncode(text["notFound.linksNoSearch"]).Replace("{home}", home, StringComparison.Ordinal)}</p>
		               </article></main>
		               </body>
		               </html>

		               """;

		fs.File.WriteAllText(path, config.Build.Minify ? HtmlMinifier.Minify(html) : html);
		logger.LogInformation("Generated a plain 404.html");
	}

	private int GenerateSectionIndexPages(BuildContext context, string outputDir, List<PageWrite> pageWrites)
	{
		IFileSystem fs = context.FileSystem;
		string basePath = context.Config.Build.BasePath;
		string basePrefix = string.IsNullOrEmpty(basePath) || basePath == "/" ? "" : "/" + basePath.Trim('/');
		int count = 0;
		SectionTargets targets = new(pageWrites.Select(w => w.Page), NavigationOrder.Routes(context.Navigation));

		// The planned paths are full and normalized, and every one is inside the output directory.
		// Comparing raw combined paths let a route with ".." walk "parents" above the output and
		// drop redirect pages into the project folder and beyond.
		var dirsWithIndex = new HashSet<string>(
			pageWrites.Select(w => fs.Path.GetDirectoryName(w.FullPath)!), StringComparer.OrdinalIgnoreCase);

		// For each directory that has an index.html, check whether its parent
		// directory is missing an index.html. If so, generate a redirect.
		var processed = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

		foreach (string dir in dirsWithIndex.Order(StringComparer.Ordinal))
		{
			// Walk up from each page directory, generating redirects for any
			// ancestor (up to but not including the output root) that lacks index.html.
			string? parent = fs.Path.GetDirectoryName(dir);
			while (parent != null
			       && parent.Length > outputDir.Length
			       && OutputPaths.IsSameOrUnder(parent, outputDir))
			{
				if (!processed.Add(parent))
				{
					break; // already handled this parent
				}

				string parentIndex = fs.Path.Combine(parent, "index.html");
				if (fs.File.Exists(parentIndex))
					// This directory already has an index page; stop walking up.
				{
					break;
				}

				string relativeDir = parent[outputDir.Length..]
					.Trim(fs.Path.DirectorySeparatorChar, fs.Path.AltDirectorySeparatorChar)
					.Replace('\\', '/');
				if (targets.FirstPageUnder("/" + relativeDir) is not { } target)
				{
					parent = fs.Path.GetDirectoryName(parent);
					continue;
				}

				// Root-relative, like every other link on the site. "./child/" resolved against the
				// parent when a host served /docs/guide without a trailing slash, sending the
				// browser to /docs/child/ instead of /docs/guide/child/.
				string redirectUrl = $"{basePrefix}/{target.Route.Trim('/')}/";
				fs.File.WriteAllText(parentIndex, SectionRedirectHtml(context.Config, target, redirectUrl));
				count++;

				string relativePath = parentIndex[outputDir.Length..].TrimStart(
					fs.Path.DirectorySeparatorChar, fs.Path.AltDirectorySeparatorChar);
				logger.LogDebug("Generated section redirect: {Path} -> {Target}", relativePath, redirectUrl);

				parent = fs.Path.GetDirectoryName(parent);
			}
		}

		if (count > 0)
		{
			logger.LogInformation("Generated {Count} section index redirect(s)", count);
		}

		return count;
	}

	/// <summary>
	///     Warns about pages that would be written to the same file.
	/// </summary>
	/// <remarks>
	///     Each page is written to <c>{route}/index.html</c>, so pages sharing a route overwrite
	///     each other and only the last survives, with nothing reported. It happens with two
	///     <c>route:</c> overrides, or a plugin whose <c>routePrefix</c> is <c>/api</c> on a site
	///     that also documents C# projects. Routes that differ only by case are included because
	///     they collide on Windows and macOS.
	/// </remarks>
	private void ReportDuplicateRoutes(BuildContext context)
	{
		IEnumerable<IGrouping<string, DocPage>> duplicates = context.Pages
			.Where(p => context.IncludeDrafts || p.FrontMatter.Visibility != PageVisibility.Draft)
			.GroupBy(p => "/" + p.Route.Trim('/'), StringComparer.OrdinalIgnoreCase)
			.Where(g => g.Count() > 1);

		foreach (IGrouping<string, DocPage> group in duplicates)
		{
			string pages = string.Join(", ", group.Select(p =>
				string.IsNullOrEmpty(p.SourcePath) ? $"generated page '{p.FrontMatter.Title}'" : p.SourcePath));
			context.Diagnostics.Warning(
				$"{group.Count()} pages share the route '{group.Key}' ({pages}); only the last one is written", Name);
		}
	}

	/// <summary>
	///     The page a section folder without an index page redirects to. The stub tells search engines
	///     not to index it, and names the target as canonical when <c>site.url</c> is set: a relative
	///     canonical URL is invalid.
	/// </summary>
	private static string SectionRedirectHtml(SiteConfig config, DocPage target, string redirectUrl)
	{
		string title = HttpUtility.HtmlEncode(target.FrontMatter.Title);
		string href = HttpUtility.HtmlAttributeEncode(redirectUrl);
		string canonical = SiteUrls.Absolute(config.Site.Url, config.Build.BasePath, target.Route);
		string canonicalLink = canonical.Length > 0
			? $"<link rel=\"canonical\" href=\"{HttpUtility.HtmlAttributeEncode(canonical)}\">"
			: "";
		ThemeText text = ThemeText.For(config);
		string link = $"<a href=\"{href}\">{title}</a>";

		return $"""
		        <!DOCTYPE html>
		        {HtmlStart(config, text)}
		        <head>
		        <meta charset="utf-8">
		        <meta name="viewport" content="width=device-width, initial-scale=1">
		        <meta name="robots" content="noindex">
		        <title>{title}</title>
		        <meta http-equiv="refresh" content="0; url={href}">{canonicalLink}
		        </head>
		        <body>
		        <p>{HttpUtility.HtmlEncode(text["redirect.section"]).Replace("{link}", link, StringComparison.Ordinal)}</p>
		        </body>
		        </html>

		        """;
	}

	/// <summary>The <c>&lt;html&gt;</c> start tag of a page MokaDocs writes itself, with the site's language and direction.</summary>
	internal static string HtmlStart(SiteConfig config, ThemeText text) =>
		$"<html lang=\"{HttpUtility.HtmlAttributeEncode(text.Language)}\" dir=\"{SiteLanguages.Direction(text.Language, config.Site.Direction)}\">";

	private sealed record PageWrite(DocPage Page, string FullPath);

	/// <summary>
	///     Where a section folder leads: its first page in sidebar order, else the first page below it
	///     by <c>order</c> and route, public pages first. The alphabetically first subfolder was used,
	///     which skipped the page the sidebar opens the section with.
	/// </summary>
	private sealed class SectionTargets(IEnumerable<DocPage> pages, List<string> sidebarRoutes)
	{
		private readonly Dictionary<string, DocPage> _pages = pages
			.GroupBy(p => Normalize(p.Route), StringComparer.OrdinalIgnoreCase)
			.ToDictionary(g => g.Key, g => g.Last(), StringComparer.OrdinalIgnoreCase);

		public DocPage? FirstPageUnder(string folderRoute)
		{
			string prefix = Normalize(folderRoute) + "/";
			foreach (string route in sidebarRoutes)
			{
				if (_pages.TryGetValue(Normalize(route), out DocPage? page)
				    && Normalize(route).StartsWith(prefix, StringComparison.OrdinalIgnoreCase))
				{
					return page;
				}
			}

			return _pages
				.Where(p => p.Key.StartsWith(prefix, StringComparison.OrdinalIgnoreCase))
				.Select(p => p.Value)
				.OrderBy(p => p.FrontMatter.Visibility == PageVisibility.Public ? 0 : 1)
				.ThenBy(p => p.FrontMatter.Order)
				.ThenBy(p => p.Route, StringComparer.OrdinalIgnoreCase)
				.FirstOrDefault();
		}

		private static string Normalize(string route) => "/" + route.Trim('/');
	}
}
